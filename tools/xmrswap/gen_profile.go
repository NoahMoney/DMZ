//go:build ignore

// gen_profile writes profile_gen.go from mainnet_profile.json (MT-B16). Run it from tools/ as `go generate ./xmrswap`.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
)

type tier struct {
	Confirmations uint64  `json:"confirmations"`
	FromPiconero  *uint64 `json:"from_piconero"`
}

func main() {
	raw, err := os.ReadFile("mainnet_profile.json")
	if err != nil {
		log.Fatal(err)
	}
	var p struct {
		DeroBlockSeconds   uint64 `json:"dero_block_seconds"`
		MoneroBlockSeconds uint64 `json:"monero_block_seconds"`
		StableBlocks       uint64 `json:"stable_blocks"`
		ClaimMargin        uint64 `json:"claim_margin"`
		T1Min              uint64 `json:"t1_min"`
		T1Default          uint64 `json:"t1_default"`
		T1Max              uint64 `json:"t1_max"`
		T2Min              uint64 `json:"t2_min"`
		T2MinusT1          uint64 `json:"t2_minus_t1"`
		T2Max              uint64 `json:"t2_max"`
		GateDeadline       uint64 `json:"gate_deadline"`
		K                  uint64 `json:"k"`
		StipendFloor       uint64 `json:"stipend_floor"`
		ConfirmationsFloor uint64 `json:"confirmations_floor"`
		Tiers              []tier `json:"confirmation_tiers"`
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	if err := dec.Decode(&p); err != nil {
		log.Fatal(err)
	}
	if p.T1Default < p.T1Min || len(p.Tiers) == 0 {
		log.Fatal("mainnet_profile.json: t1_default is below t1_min, or there are no tiers")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_profile.go from mainnet_profile.json; DO NOT EDIT.\n\npackage xmrswap\n\n")
	b.WriteString("// The mainnet profile's values (MT-B16); swap.go's defaults are these. Edit mainnet_profile.json, then go generate.\n")
	b.WriteString("const (\n")
	for _, kv := range []struct {
		name string
		v    uint64
	}{
		{"profileDeroBlockSeconds", p.DeroBlockSeconds}, {"profileMoneroBlockSeconds", p.MoneroBlockSeconds},
		{"profileStableBlocks", p.StableBlocks}, {"profileClaimMargin", p.ClaimMargin},
		{"profileT1Min", p.T1Min}, {"profileT1Default", p.T1Default}, {"profileT1Max", p.T1Max},
		{"profileT2Min", p.T2Min}, {"profileT2MinusT1", p.T2MinusT1}, {"profileT2Max", p.T2Max},
		{"profileGateDeadline", p.GateDeadline}, {"profileK", p.K}, {"profileStipendFloor", p.StipendFloor},
		{"profileConfirmationsFloor", p.ConfirmationsFloor},
	} {
		fmt.Fprintf(&b, "\t%s uint64 = %d\n", kv.name, kv.v)
	}
	b.WriteString(")\n\n// profileTiers are the confirmation tiers by notional; a nil threshold is one the operator has not set.\n")
	b.WriteString("var profileTiers = []ProfileTier{\n")
	for _, t := range p.Tiers {
		if t.FromPiconero == nil {
			fmt.Fprintf(&b, "\t{Confirmations: %d},\n", t.Confirmations)
		} else {
			fmt.Fprintf(&b, "\t{Confirmations: %d, FromPiconero: profileAmount(%d)},\n", t.Confirmations, *t.FromPiconero)
		}
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("profile_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
