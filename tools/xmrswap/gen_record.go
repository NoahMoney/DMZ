//go:build ignore

// gen_record writes record_gen.go from deploy/networks.json (MT-A18): each DERO network's htlc.bas scid and its
// xmrTreasury, the Monero address DMZ's swap fee goes to. Run it from tools/ as `go generate ./xmrswap`.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	raw, err := os.ReadFile(filepath.Join("..", "..", "deploy", "networks.json"))
	if err != nil {
		log.Fatal(err)
	}
	var rec map[string]json.RawMessage
	if err := json.Unmarshal(raw, &rec); err != nil {
		log.Fatal(err)
	}
	var nets []string
	for k := range rec {
		if !strings.HasPrefix(k, "_") {
			nets = append(nets, k)
		}
	}
	sort.Strings(nets)
	type block struct {
		HTLC        string `json:"htlc"`
		XmrTreasury string `json:"xmrTreasury"`
	}
	blocks := map[string]block{}
	for _, k := range nets {
		var n block
		if err := json.Unmarshal(rec[k], &n); err != nil {
			log.Fatalf("%s: %v", k, err)
		}
		blocks[k] = n
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_record.go from deploy/networks.json; DO NOT EDIT.\n\npackage xmrswap\n\n")
	b.WriteString("// recordedHTLC is htlc.bas's scid on each DERO network as deploy/networks.json records it (\"\" = not deployed there).\n")
	b.WriteString("var recordedHTLC = map[string]string{\n")
	for _, k := range nets {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, blocks[k].HTLC)
	}
	b.WriteString("}\n\n")
	b.WriteString("// recordedXmrTreasury is the Monero address DMZ's swap fee goes to on each DERO network, as deploy/networks.json's\n")
	b.WriteString("// xmrTreasury records it (\"\" = none recorded).\n")
	b.WriteString("var recordedXmrTreasury = map[string]string{\n")
	for _, k := range nets {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, blocks[k].XmrTreasury)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("record_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
