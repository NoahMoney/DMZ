#!/usr/bin/env bash
# Bring up two monero-wallet-rpc on Monero STAGENET, one per party of a swap, on the harness's stagenet monerod
# (tools/regtest/stagenet-up.sh), inside WSL2, reachable from Windows at 127.0.0.1:$SW_ALICE_PORT (alice) and
# 127.0.0.1:$SW_BOB_PORT (bob). For MT-B19, the stagenet run of all three exits (tools/simhtlc -stagenet).
#
#   tools/regtest/stagenet-wallets-up.sh           start both (or report them), once a stagenet monerod answers
#   tools/regtest/stagenet-wallets-up.sh --create  also create the two named wallets if they are absent — only once
#                                                  the node is synchronized, so a new wallet starts at the tip and never
#                                                  scans the chain from an old height — and print their addresses
#
# The same pinned monero-wallet-rpc 0.18.5.1 as the regtest harness, run with --stagenet, so it refuses a daemon on any
# other network; --daemon-address 127.0.0.1:$STAGENET_RPC_PORT, --trusted-daemon (our own node, on this machine). RPC
# bound to 127.0.0.1 with --disable-rpc-login, as in the regtest harness: loopback only, and the companion warns about
# it off mainnet (on mainnet it would refuse). Ports: 38088 is monero's default stagenet wallet RPC port
# (docs.getmonero.org/infrastructure/networks), 38087 beside it for the second party. The wallet files live on WSL's own
# disk, $HOME/.dmz-regtest/stagenet-wallets/<party>, like the node's chain.
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"

SW_ALICE_PORT="${STAGENET_WALLET_RPC_PORT:-38088}"
SW_BOB_PORT="${STAGENET_WALLET_RPC_PORT2:-38087}"
SW_ALICE_WALLET="${STAGENET_ALICE_WALLET:-xmrswap-stagenet-alice}"
SW_BOB_WALLET="${STAGENET_BOB_WALLET:-xmrswap-stagenet-bob}"
CREATE=0
[ "${1:-}" = "--create" ] && CREATE=1

need_wsl
WHOME="$(wsl_exec printenv HOME | tr -d '\r')"
MBIN="$WHOME/.dmz-regtest/monero-v$MONERO_VERSION"
WDIR="$WHOME/.dmz-regtest/stagenet-wallets"
LDIR="$REPO/.sim/stagenet-wallets"

got="$(wsl_exec sha256sum "$MBIN/monero-wallet-rpc" 2>/dev/null | tr -d '\r' | awk '{print $1}' || true)"
[ "$got" = "$MONERO_WALLET_RPC_SHA256" ] ||
	die "monero-wallet-rpc in $MBIN is not the pinned $MONERO_VERSION build (sha256 '$got'): run tools/regtest/monero-up.sh or stagenet-up.sh once to extract it"

info() { curl -sf --max-time 30 "http://127.0.0.1:$STAGENET_RPC_PORT/json_rpc" -H 'content-type: application/json' -d '{"jsonrpc":"2.0","id":"0","method":"get_info"}' | tr -d ' \n'; }
is_stagenet() { info | grep -q '"nettype":"stagenet"'; }
is_synced() { info | grep -q '"synchronized":true'; }
wallet_probe() { curl -sf --max-time 5 "http://127.0.0.1:$1/json_rpc" -H 'content-type: application/json' -d '{"jsonrpc":"2.0","id":"0","method":"get_version"}' | grep -q '"version"'; }
wrpc() { curl -s --max-time 300 "http://127.0.0.1:$1/json_rpc" -H 'content-type: application/json' -d "{\"jsonrpc\":\"2.0\",\"id\":\"0\",\"method\":\"$2\",\"params\":$3}"; }

is_stagenet || die "no STAGENET monerod answers on 127.0.0.1:$STAGENET_RPC_PORT (tools/regtest/stagenet-up.sh starts it): a wallet-rpc is started against nothing else"

mkdir -p "$LDIR" "$DATA"
wsl_exec mkdir -p "$WDIR/alice" "$WDIR/bob"

start_wallet_rpc() {
	local name="$1" port="$2" party="$3" pid
	if port_listening "$port"; then
		# Something already listens there. It is used only if it can be shown to be what this script starts: the pinned
		# monero-wallet-rpc, --stagenet, its RPC on 127.0.0.1 at this port, inside WSL (its command line from pgrep -af,
		# its running image hashed; common.sh stagenet_wallet_rpc_pid). Anything else — another program, a wallet-rpc on
		# another network or bound elsewhere, a build that is not the pinned one, a listener on the Windows side — is
		# refused and never talked to.
		pid="$(stagenet_wallet_rpc_pid "$MBIN/monero-wallet-rpc" "$port")"
		[ -n "$pid" ] || die "port $port is taken by something this script cannot show is the pinned monero-wallet-rpc $MONERO_VERSION running --stagenet on 127.0.0.1:$port inside WSL: refusing to use it (stop it, or choose other ports with STAGENET_WALLET_RPC_PORT and STAGENET_WALLET_RPC_PORT2)"
		wallet_probe "$port" || die "the stagenet monero-wallet-rpc on port $port (pid $pid in WSL) does not answer get_version"
		say "$name already running at http://127.0.0.1:$port (pid $pid in WSL: the pinned $MONERO_VERSION, --stagenet)"
		return 0
	fi
	cat >"$LDIR/run-$name.sh" <<EOF
#!/usr/bin/env bash
# generated by tools/regtest/stagenet-wallets-up.sh
echo \$\$ > "$WDIR/$name.pid"
exec "$MBIN/monero-wallet-rpc" --stagenet --daemon-address 127.0.0.1:$STAGENET_RPC_PORT --trusted-daemon \\
	--rpc-bind-ip 127.0.0.1 --rpc-bind-port $port --disable-rpc-login \\
	--wallet-dir "$WDIR/$party" --log-file "$WDIR/$name.log" --log-level 0 --non-interactive \\
	< /dev/null >> "$WDIR/$name.out" 2>&1
EOF
	say "starting $name ($MONERO_VERSION, --stagenet) in WSL on 127.0.0.1:$port, wallet dir $WDIR/$party"
	start_detached "$name" "$(to_wsl "$LDIR/run-$name.sh")"
	if ! wait_for 120 "$name" wallet_probe "$port"; then
		wsl_exec tail -n 20 "$WDIR/$name.out" "$WDIR/$name.log" >&2 || true
		die "$name did not answer on 127.0.0.1:$port within 120 s"
	fi
	# what answers must be what was started: the pid its launcher wrote, and that process the pinned --stagenet wallet-rpc
	pid="$(wsl_exec cat "$WDIR/$name.pid" 2>/dev/null | tr -d '\r' || true)"
	if [ -z "$pid" ] || [ "$(stagenet_wallet_rpc_pid "$MBIN/monero-wallet-rpc" "$port" "$pid")" != "$pid" ]; then
		die "what answers on 127.0.0.1:$port is not the monero-wallet-rpc this script started (its pid file says '$pid'): look at it before starting again"
	fi
	say "$name up at http://127.0.0.1:$port (pid $pid in WSL)"
}
start_wallet_rpc stagenet-wallet-alice "$SW_ALICE_PORT" alice
start_wallet_rpc stagenet-wallet-bob "$SW_BOB_PORT" bob

if [ "$CREATE" = 1 ]; then
	is_synced || die "the stagenet node is not synchronized yet: the wallets are created only at the tip, so a new wallet never scans the chain from an old height"
	for pair in "$SW_ALICE_PORT:$SW_ALICE_WALLET" "$SW_BOB_PORT:$SW_BOB_WALLET"; do
		port="${pair%%:*}"
		w="${pair#*:}"
		if wrpc "$port" open_wallet "{\"filename\":\"$w\",\"password\":\"\"}" | grep -q '"result"'; then
			say "$w exists; opened"
		else
			wrpc "$port" create_wallet "{\"filename\":\"$w\",\"password\":\"\",\"language\":\"English\"}" | grep -q '"result"' || die "create_wallet $w on 127.0.0.1:$port failed"
			say "created $w"
		fi
		addr="$(wrpc "$port" get_address '{"account_index":0}' | tr -d ' \n' | grep -o '"address":"[0-9A-Za-z]*"' | head -1 | cut -d'"' -f4)"
		# a stagenet standard address starts with 5 (mainnet 4, testnet 9 or A): anything else is not this network
		case "$addr" in 5*) ;; *) die "$w holds $addr, which is not a stagenet address" ;; esac
		say "$w: $addr"
	done
	say "fund $SW_ALICE_WALLET's address above before the run (tools/regtest/README.md, 'The stagenet swap run')"
fi
say "stagenet wallets up: alice http://127.0.0.1:$SW_ALICE_PORT, bob http://127.0.0.1:$SW_BOB_PORT (loopback, no login), node 127.0.0.1:$STAGENET_RPC_PORT"
