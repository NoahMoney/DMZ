#!/usr/bin/env bash
# Bring up one monerod on Monero REGTEST and one monero-wallet-rpc on it, inside WSL2, reachable from Windows at
# 127.0.0.1:$MONERO_RPC_PORT (daemon) and 127.0.0.1:$MONERO_WALLET_RPC_PORT (wallet-rpc, no login).
#
#   tools/regtest/monero-up.sh      start whatever is not running yet, then wait until both answer
#
# Regtest only: --regtest --offline (no peers, no DNS), P2P bound to 127.0.0.1. The chain is kept across restarts
# (--keep-fakechain) in .sim/regtest/monero/chain; wallet files in .sim/regtest/monero/wallets (both git-ignored).
#
# The binaries run from the WSL distro's own filesystem ($HOME/.dmz-regtest/monero-v<version>), extracted from the
# pinned tarball in vendor/regtest/dl and checked against pins.env on every start: Windows Defender quarantines
# monerod and monero-wallet-rpc (heuristic CoinMiner/Wacatac detections) anywhere on the Windows drive, and this
# harness does not add antivirus exclusions — that is the operator's decision (README.md, "Why WSL").
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"

need_wsl
MDIR="$DATA/monero"
MW="$(to_wsl "$MDIR")"
TARBALL="$VENDOR/dl/$MONERO_TARBALL"
WHOME="$(wsl_exec printenv HOME | tr -d '\r')"
MBIN="$WHOME/.dmz-regtest/monero-v$MONERO_VERSION"

bin_hashes() { wsl_exec sha256sum "$MBIN/monerod" "$MBIN/monero-wallet-rpc" 2>/dev/null | tr -d '\r' | awk '{printf "%s ", $1}'; }
WANT="$MONEROD_SHA256 $MONERO_WALLET_RPC_SHA256 "
if [ "$(bin_hashes || true)" != "$WANT" ]; then
	check_sha256 "$TARBALL" "$MONERO_TARBALL_SHA256" "the Monero $MONERO_VERSION release tarball"
	say "extracting Monero $MONERO_VERSION into WSL at $MBIN"
	wsl_exec bash -c "rm -rf '$MBIN' && mkdir -p '$MBIN' && tar -xjf '$(to_wsl "$TARBALL")' -C '$MBIN' --strip-components=1"
	[ "$(bin_hashes || true)" = "$WANT" ] || die "monerod / monero-wallet-rpc in $MBIN do not match pins.env after extraction"
fi

daemon_rpc() { curl -sf --max-time 5 "http://127.0.0.1:$MONERO_RPC_PORT/json_rpc" -H 'content-type: application/json' -d "{\"jsonrpc\":\"2.0\",\"id\":\"0\",\"method\":\"$1\"}"; }
daemon_probe() { daemon_rpc get_info | tr -d ' \n' | grep -q '"nettype":"fakechain"'; }
wallet_probe() { curl -sf --max-time 5 "http://127.0.0.1:$1/json_rpc" -H 'content-type: application/json' -d '{"jsonrpc":"2.0","id":"0","method":"get_version"}' | grep -q '"version"'; }

mkdir -p "$MDIR/chain" "$MDIR/ringdb"

# --- monerod ---
if port_listening "$MONERO_RPC_PORT"; then
	daemon_probe || die "port $MONERO_RPC_PORT is taken by something that is not a regtest monerod"
	say "monerod already running (regtest) at http://127.0.0.1:$MONERO_RPC_PORT"
else
	port_listening "$MONERO_P2P_PORT" && die "P2P port $MONERO_P2P_PORT is taken"
	cat >"$MDIR/run-monerod.sh" <<EOF
#!/usr/bin/env bash
# generated by tools/regtest/monero-up.sh
echo \$\$ > "$MW/monerod.pid"
exec "$MBIN/monerod" --regtest --offline --fixed-difficulty 1 --keep-fakechain \\
	--data-dir "$MW/chain" --log-file "$MW/monerod.log" --log-level 0 \\
	--rpc-bind-ip 127.0.0.1 --rpc-bind-port $MONERO_RPC_PORT \\
	--p2p-bind-ip 127.0.0.1 --p2p-bind-port $MONERO_P2P_PORT \\
	--no-zmq --no-igd --disable-dns-checkpoints --non-interactive \\
	< /dev/null >> "$MW/monerod.out" 2>&1
EOF
	say "starting monerod $MONERO_VERSION (regtest) in WSL, log $MDIR/monerod.log"
	start_detached monerod "$MW/run-monerod.sh"
	if ! wait_for 120 "monerod RPC" daemon_probe; then
		tail -n 20 "$MDIR/monerod.out" "$MDIR/monerod.log" >&2 || true
		die "monerod did not answer as a regtest daemon on 127.0.0.1:$MONERO_RPC_PORT within 120 s"
	fi
fi

# --- two monero-wallet-rpc, one per party, each with its own wallet dir (a wallet file is opened by one rpc only) ---
# No --testnet/--stagenet: a regtest daemon uses mainnet's address prefixes, so the wallet runs as mainnet nettype
# (monero-wallet-rpc has no --regtest). --trusted-daemon: it is our own daemon, on this machine.
# --allow-mismatched-daemon-version: a regtest chain is at hard fork v16 from height 1, and a mainnet-nettype wallet
# checks every block against mainnet's fork table, so without it every refresh fails with "Unexpected hard fork
# version v16 at height 1" (measured). In v0.18.5.1 the flag skips exactly that per-block check (wallet2.cpp:3525)
# and the daemon fork-table check on connect (wallet2.cpp:6375), nothing else. It is a harness setting: a person's
# wallet on mainnet never needs it, and a companion must not tell anyone to use it.
start_wallet_rpc() {
	local name="$1" port="$2" wdir="$3"
	if port_listening "$port"; then
		wallet_probe "$port" || die "port $port is taken by something that is not monero-wallet-rpc"
		say "$name already running at http://127.0.0.1:$port"
		return 0
	fi
	mkdir -p "$MDIR/$wdir"
	cat >"$MDIR/run-$name.sh" <<EOF
#!/usr/bin/env bash
# generated by tools/regtest/monero-up.sh
echo \$\$ > "$MW/$name.pid"
exec "$MBIN/monero-wallet-rpc" --daemon-address 127.0.0.1:$MONERO_RPC_PORT --trusted-daemon --allow-mismatched-daemon-version \\
	--rpc-bind-ip 127.0.0.1 --rpc-bind-port $port --disable-rpc-login \\
	--wallet-dir "$MW/$wdir" --shared-ringdb-dir "$MW/ringdb" \\
	--log-file "$MW/$name.log" --log-level 0 --non-interactive \\
	< /dev/null >> "$MW/$name.out" 2>&1
EOF
	say "starting $name ($MONERO_VERSION) in WSL on 127.0.0.1:$port, wallet dir $MDIR/$wdir"
	start_detached "$name" "$MW/run-$name.sh"
	if ! wait_for 120 "$name" wallet_probe "$port"; then
		tail -n 20 "$MDIR/$name.out" "$MDIR/$name.log" >&2 || true
		die "$name did not answer on 127.0.0.1:$port within 120 s"
	fi
}
start_wallet_rpc wallet-rpc "$MONERO_WALLET_RPC_PORT" wallets
start_wallet_rpc wallet-rpc-2 "$MONERO_WALLET_RPC_PORT2" wallets-2

say "monero up: daemon http://127.0.0.1:$MONERO_RPC_PORT"
say "  wallet-rpc   http://127.0.0.1:$MONERO_WALLET_RPC_PORT/json_rpc  (no login; wallet dir $MDIR/wallets)"
say "  wallet-rpc-2 http://127.0.0.1:$MONERO_WALLET_RPC_PORT2/json_rpc  (no login; wallet dir $MDIR/wallets-2)"
say "  both start with no wallet open: create_wallet or open_wallet before a companion calls get_height/get_address"
