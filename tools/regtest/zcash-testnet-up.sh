#!/usr/bin/env bash
# Bring up zebrad 6.3.0 on the Zcash TESTNET — the public test network, never mainnet — inside WSL2, and sync it.
#
#   tools/regtest/zcash-testnet-up.sh                 start it; when it is running, check it is testnet and print the
#                                                     height, the target height, the size on disk, the peers and an
#                                                     estimated finish
#   tools/regtest/zcash-testnet-up.sh --restart-gate  replace the running rpcgate with the current build, leaving
#                                                     zebrad and its sync alone
#
# The node: the same pinned, verified zebrad as the regtest harness, `network = "Testnet"`, no mainnet peers in its
# config, P2P listening on 127.0.0.1 only (no peer can connect in; Zebra has no UPnP), its state on WSL's own ext4
# filesystem (a RocksDB of ~10 GB syncs far faster there than over the /mnt/c mount). Zebra 6.3.0 has no update check
# and no telemetry: its end-of-support task compares heights on mainnet only, and its metrics, tracing, OpenTelemetry
# and health endpoints are all off unless configured, and none is.
#
# The RPC: zebrad cannot limit its RPC to a set of methods, so its own RPC listens on an internal loopback port with
# its cookie inside WSL, and clients get tools/regtest/rpcgate on 127.0.0.1:$ZCASH_TESTNET_RPC_PORT, which serves only
# the seven methods tools/zecswap calls, behind a cookie of its own at .sim/zcash-testnet/.cookie. The gate runs under
# a wsl.exe host of its own, so a new build of it replaces the old without stopping the sync, and the status report
# warns when the gate running is not the build in vendor/regtest/bin.
#
# Testnet only: the node must answer getblockhash 0 with the testnet genesis block and getblockchaininfo with chain
# "test"; anything else — mainnet's genesis, regtest's, no answer — stops it and the gate, and the script fails.
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"

need_wsl
TDIR="$REPO/.sim/zcash-testnet"
TW="$(to_wsl "$TDIR")"
WHOME="$(wsl_exec printenv HOME | tr -d '\r')"
WSTATE="$WHOME/.dmz-regtest/zcash-testnet"
ZEBRAD="$VENDOR/zebra/zebrad"
GATE="$VENDOR/bin/rpcgate"

if [ ! -f "$ZEBRAD" ]; then
	check_sha256 "$VENDOR/dl/$ZEBRA_TARBALL" "$ZEBRA_TARBALL_SHA256" "the zebrad release tarball"
	mkdir -p "$VENDOR/zebra"
	wsl_exec tar -xzf "$(to_wsl "$VENDOR/dl/$ZEBRA_TARBALL")" -C "$(to_wsl "$VENDOR/zebra")"
fi
check_sha256 "$ZEBRAD" "$ZEBRAD_SHA256" "zebrad $ZEBRA_VERSION"
if [ ! -f "$GATE" ] || [ "$REGTEST_HERE/rpcgate/main.go" -nt "$GATE" ]; then
	say "building rpcgate (linux/amd64, standard library only)"
	mkdir -p "$VENDOR/bin"
	(cd "$REPO/tools" && GOOS=linux GOARCH=amd64 CGO_ENABLED=0 go build -trimpath -o "$(cygpath -m "$GATE")" ./regtest/rpcgate) ||
		die "rpcgate did not build"
fi

rpc() {
	[ -f "$TDIR/.cookie" ] || return 1
	curl -sf --max-time 15 -u "$(cat "$TDIR/.cookie")" -H 'content-type: application/json' \
		-d "{\"jsonrpc\":\"1.0\",\"id\":\"t\",\"method\":\"$1\",\"params\":$2}" "http://127.0.0.1:$ZCASH_TESTNET_RPC_PORT/"
}
answers() { rpc getblockchaininfo '[]' | grep -q '"chain"'; }
genesis() { rpc getblockhash '[0]' | grep -o '"result":"[0-9a-f]*"' | cut -d'"' -f4; }
chain() { rpc getblockchaininfo '[]' | tr -d ' \n' | grep -o '"chain":"[a-z]*"' | cut -d'"' -f4; }
gate_port_free() { ! port_listening "$ZCASH_TESTNET_RPC_PORT"; }
# peers are read from zebrad's own RPC inside WSL: getpeerinfo is not one of the methods the gate serves
peers() {
	wsl_exec bash -c "curl -s --max-time 10 -u \"\$(cat '$WSTATE/.cookie')\" -H 'content-type: application/json' \
		-d '{\"jsonrpc\":\"1.0\",\"id\":\"p\",\"method\":\"getpeerinfo\",\"params\":[]}' http://127.0.0.1:$ZCASH_TESTNET_ZEBRAD_RPC_PORT/ |
		grep -o '\"addr\"' | wc -l" 2>/dev/null | tr -d '\r'
}

# refuse_unless_testnet stops everything and fails unless the node is on testnet
refuse_unless_testnet() {
	local g c
	g="$(genesis || true)"
	c="$(chain || true)"
	if [ "$g" != "$ZCASH_TESTNET_GENESIS" ] || [ "$c" != "test" ]; then
		bash "$REGTEST_HERE/zcash-testnet-down.sh" >/dev/null 2>&1 || true
		die "the node on 127.0.0.1:$ZCASH_TESTNET_RPC_PORT is not Zcash testnet (chain \"$c\", block 0 $g); stopped it"
	fi
}

# start_gate starts rpcgate under a wsl.exe host of its own and records the sha256 of the build it started
start_gate() {
	cat >"$TDIR/run-rpcgate.sh" <<EOF
#!/usr/bin/env bash
# generated by tools/regtest/zcash-testnet-up.sh
rm -f "$TW/.cookie"
echo \$\$ > "$TW/rpcgate.pid"
exec "$(to_wsl "$GATE")" -listen 127.0.0.1:$ZCASH_TESTNET_RPC_PORT -upstream http://127.0.0.1:$ZCASH_TESTNET_ZEBRAD_RPC_PORT/ \\
	-upstream-cookie "$WSTATE/.cookie" -cookie-out "$TW/.cookie" >> "$TW/rpcgate.log" 2>&1
EOF
	start_detached zcash-testnet-rpcgate "$TW/run-rpcgate.sh"
	sha256sum "$GATE" | cut -d' ' -f1 >"$TDIR/rpcgate.sha256"
}

# stop_gate ends the gate and its wsl.exe host, and waits for its port to be free
stop_gate() {
	if [ -f "$TDIR/rpcgate.pid" ]; then
		wsl_exec kill "$(cat "$TDIR/rpcgate.pid")" 2>/dev/null || true
	fi
	stop_winpid zcash-testnet-rpcgate
	rm -f "$TDIR/rpcgate.pid" "$TDIR/rpcgate.sha256" "$TDIR/.cookie"
	wait_for 30 "the old rpcgate to exit" gate_port_free || die "port $ZCASH_TESTNET_RPC_PORT is still taken 30 s after stopping rpcgate"
}

progress() {
	local j h t db p now
	j="$(rpc getblockchaininfo '[]' | tr -d ' \n')" || { say "no answer from 127.0.0.1:$ZCASH_TESTNET_RPC_PORT"; return 1; }
	h="$(echo "$j" | grep -o '"blocks":[0-9]*' | cut -d: -f2)"
	t="$(echo "$j" | grep -o '"estimatedheight":[0-9]*' | cut -d: -f2)"
	db="$(wsl_exec du -sb "$WSTATE/state" 2>/dev/null | tr -d '\r' | cut -f1)"
	p="$(peers || true)"
	now="$(date +%s)"
	echo -e "$now\t$h\t$t\t${db:-0}\t${p:-0}" >>"$TDIR/progress.tsv"
	# the target is the largest of zebrad's estimatedheight, the height, and the last checkpoint this zebrad ships
	# the rate is over the last five readings (the sync slows as blocks fill up, so the average since the start
	# would promise too early a finish)
	awk -v n="$now" -v h="$h" -v t="$t" -v f="$ZCASH_TESTNET_TIP_FLOOR" -v db="${db:-0}" -v p="${p:-?}" '{T[NR]=$1; H[NR]=$2}
		END {
			k = (NR > 5) ? NR - 5 : 1
			t0 = T[k]; h0 = H[k]
			tt = (t > h) ? t : h
			if (f > tt) tt = f
			printf "regtest: zcash testnet height %d of ~%d (%.1f%%), state on disk %.2f GB, %s peers", h, tt, (tt ? 100*h/tt : 0), db/1e9, p
			if (n > t0 && h > h0) {
				r = (h - h0) / (n - t0)
				printf ", %.1f blocks/s over the last %.0f min", r, (n - t0) / 60
				if (tt > h) printf ", about %.1f h to go at that rate", (tt - h) / r / 3600
			}
			printf "\n"
		}' "$TDIR/progress.tsv"
}

if [ "${1:-}" = "--restart-gate" ]; then
	if [ ! -f "$TDIR/zebrad.pid" ] || ! wsl_exec kill -0 "$(cat "$TDIR/zebrad.pid")" 2>/dev/null; then
		die "zebrad is not running: start the node and its gate together with $0"
	fi
	stop_gate
	start_gate
	wait_for 60 "rpcgate" answers || die "rpcgate did not answer on 127.0.0.1:$ZCASH_TESTNET_RPC_PORT within 60 s (see $TDIR/rpcgate.log)"
	refuse_unless_testnet
	say "rpcgate restarted on the build in vendor/regtest/bin (sha256 $(cat "$TDIR/rpcgate.sha256")); zebrad was not touched"
	exit 0
fi

if port_listening "$ZCASH_TESTNET_RPC_PORT"; then
	answers || die "port $ZCASH_TESTNET_RPC_PORT is taken by something that is not this harness's rpcgate"
	refuse_unless_testnet
	if [ "$(cat "$TDIR/rpcgate.sha256" 2>/dev/null)" != "$(sha256sum "$GATE" | cut -d' ' -f1)" ]; then
		say "WARNING: the rpcgate running is not the build in vendor/regtest/bin (tools/regtest/rpcgate changed since it started); replace it with $0 --restart-gate"
	fi
	progress
	exit 0
fi
for port in "$ZCASH_TESTNET_ZEBRAD_RPC_PORT" "$ZCASH_TESTNET_P2P_PORT"; do
	port_listening "$port" && die "port $port is taken"
done

mkdir -p "$TDIR"
wsl_exec mkdir -p "$WSTATE/state" "$WSTATE/peers"
cat >"$TDIR/zebrad.toml" <<EOF
# generated by tools/regtest/zcash-testnet-up.sh — edits are overwritten on the next start
[network]
network = "Testnet"
listen_addr = "127.0.0.1:$ZCASH_TESTNET_P2P_PORT"
initial_mainnet_peers = []
cache_dir = "$WSTATE/peers"

[state]
cache_dir = "$WSTATE/state"

[rpc]
listen_addr = "127.0.0.1:$ZCASH_TESTNET_ZEBRAD_RPC_PORT"
enable_cookie_auth = true
cookie_dir = "$WSTATE"

[tracing]
use_color = false
filter = "info"
EOF

cat >"$TDIR/run-zebrad.sh" <<EOF
#!/usr/bin/env bash
# generated by tools/regtest/zcash-testnet-up.sh
echo \$\$ > "$TW/zebrad.pid"
exec "$(to_wsl "$ZEBRAD")" -c "$TW/zebrad.toml" start >> "$TW/zebrad.log" 2>&1
EOF

say "starting zebrad $ZEBRA_VERSION on Zcash TESTNET in WSL (state in WSL at $WSTATE), log $TDIR/zebrad.log"
start_detached zcash-testnet "$TW/run-zebrad.sh"
start_gate
if ! wait_for 180 "zebrad testnet RPC" answers; then
	tail -n 20 "$TDIR/zebrad.log" "$TDIR/rpcgate.log" >&2 || true
	bash "$REGTEST_HERE/zcash-testnet-down.sh" >/dev/null 2>&1 || true
	die "zebrad did not answer through rpcgate on 127.0.0.1:$ZCASH_TESTNET_RPC_PORT within 180 s; stopped it"
fi
refuse_unless_testnet
rm -f "$TDIR/progress.tsv"
say "zcash testnet up: RPC http://127.0.0.1:$ZCASH_TESTNET_RPC_PORT (rpcgate: zecswap's 7 methods only), cookie $TDIR/.cookie"
progress
