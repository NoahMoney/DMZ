#!/usr/bin/env bash
# Bring up one zebrad on Zcash REGTEST, inside WSL2, reachable from Windows at 127.0.0.1:$ZCASH_RPC_PORT.
#
#   tools/regtest/zcash-up.sh          start (or report the one already running) and wait until its RPC answers
#
# Regtest only: the config names network "Regtest", lists no peers, and listens for P2P on 127.0.0.1 only, so the
# node can reach no other node. Every network upgrade through NU6.3 activates at a low height (1..10), so a block
# mined now carries the current consensus branch id. State lives in .sim/regtest/zcash (git-ignored); the RPC
# cookie is .sim/regtest/zcash/.cookie ("__cookie__:<password>", HTTP basic auth).
. "$(dirname "${BASH_SOURCE[0]}")/common.sh"

need_wsl
ZDIR="$DATA/zcash"
ZEBRAD="$VENDOR/zebra/zebrad"
TARBALL="$VENDOR/dl/$ZEBRA_TARBALL"

# The binary: the one pinned, or re-extracted from the pinned (and signature-checked, see PINS.md) release tarball.
if [ ! -f "$ZEBRAD" ]; then
	check_sha256 "$TARBALL" "$ZEBRA_TARBALL_SHA256" "the zebrad release tarball"
	mkdir -p "$VENDOR/zebra"
	wsl_exec tar -xzf "$(to_wsl "$TARBALL")" -C "$(to_wsl "$VENDOR/zebra")"
fi
check_sha256 "$ZEBRAD" "$ZEBRAD_SHA256" "zebrad $ZEBRA_VERSION"

# Zebra names its Regtest "test" in getblockchaininfo (BIP 70's name for every test network), so the chain name
# cannot tell regtest from testnet. The genesis block can: this is Zebra's REGTEST_GENESIS_HASH (zcashd's too).
REGTEST_GENESIS=029f11d80ef9765602235e1bc9727e3eb6ba20839319f761fee920d63401e327
zrpc_probe() {
	[ -f "$ZDIR/.cookie" ] || return 1
	curl -sf --max-time 5 -u "$(cat "$ZDIR/.cookie")" -H 'content-type: application/json' \
		-d '{"jsonrpc":"1.0","id":"up","method":"getblockhash","params":[0]}' "http://127.0.0.1:$ZCASH_RPC_PORT/" |
		grep -q "\"result\":\"$REGTEST_GENESIS\""
}

if port_listening "$ZCASH_RPC_PORT"; then
	if zrpc_probe; then
		say "zebrad already running: regtest RPC at http://127.0.0.1:$ZCASH_RPC_PORT (cookie $ZDIR/.cookie)"
		exit 0
	fi
	die "port $ZCASH_RPC_PORT is taken by something that is not this harness's regtest zebrad"
fi
port_listening "$ZCASH_P2P_PORT" && die "P2P port $ZCASH_P2P_PORT is taken"

mkdir -p "$ZDIR/state"
ZW="$(to_wsl "$ZDIR")"
MINER="${DMZ_ZEC_MINER_ADDRESS:-$ZCASH_DEFAULT_MINER}"

cat >"$ZDIR/zebrad.toml" <<EOF
# generated by tools/regtest/zcash-up.sh — edits are overwritten on the next start
[network]
network = "Regtest"
listen_addr = "127.0.0.1:$ZCASH_P2P_PORT"
initial_mainnet_peers = []
initial_testnet_peers = []
cache_dir = false

[network.testnet_parameters]
should_allow_unshielded_coinbase_spends = true

# Canopy must be active at height 1. zebrad 6.3.0 mines only through getblocktemplate, which refuses any block
# before Canopy ("Zebra does not support generating pre-Canopy block templates") and, before Heartwood, panics
# outright ("history root is required for block templates", zebra-rpc DefaultRoots::from_coinbase) — both measured
# here. Overwinter..Canopy therefore share height 1; NU5 onwards are staggered one block apart, so the node's upgrade
# table and the branch id at each height can be seen. tools/regtest/zfund carries the same heights (regtest_params)
# and smoke-zcash.sh checks that the node agrees with them.
[network.testnet_parameters.activation_heights]
Overwinter = 1
Sapling = 1
Blossom = 1
Heartwood = 1
Canopy = 1
NU5 = 2
NU6 = 3
"NU6.1" = 4
"NU6.2" = 5
"NU6.3" = 6

[state]
cache_dir = "$ZW/state"

# debug_force_finished_sync: blocks mined by generate carry the genesis time plus one second per block (2011-02-02,
# measured), so zebrad's estimatedheight — the tip plus the time since the tip at 75 s a block — reads millions of
# blocks ahead and a client that checks it (zecswap's Sane) sees a node that is not synced. This test-only option
# makes estimatedheight the tip itself (zebra-rpc get_blockchain_info). Regtest only; README.md lists it.
[rpc]
listen_addr = "127.0.0.1:$ZCASH_RPC_PORT"
enable_cookie_auth = true
cookie_dir = "$ZW"
debug_force_finished_sync = true

[mining]
miner_address = "$MINER"

[tracing]
use_color = false
filter = "info"
EOF

cat >"$ZDIR/run-zebrad.sh" <<EOF
#!/usr/bin/env bash
# generated by tools/regtest/zcash-up.sh
echo \$\$ > "$ZW/zebrad.pid"
exec "$(to_wsl "$ZEBRAD")" -c "$ZW/zebrad.toml" start >> "$ZW/zebrad.log" 2>&1
EOF

rm -f "$ZDIR/.cookie"
say "starting zebrad $ZEBRA_VERSION (regtest) in WSL, log $ZDIR/zebrad.log"
start_detached zebrad "$ZW/run-zebrad.sh"

if ! wait_for 180 "zebrad RPC" zrpc_probe; then
	tail -n 30 "$ZDIR/zebrad.log" >&2 || true
	die "zebrad did not answer on 127.0.0.1:$ZCASH_RPC_PORT within 180 s (log above)"
fi
say "zebrad up: regtest RPC http://127.0.0.1:$ZCASH_RPC_PORT, basic auth from $ZDIR/.cookie"
